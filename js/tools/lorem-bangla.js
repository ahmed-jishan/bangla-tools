// ─── Generator ───────────────────────────────────────────────────────────────

function getRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getRandomSentences(theme = 'general', count = 5) {
  const pool = THEMES[theme]?.sentences || THEMES.general.sentences;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

function buildParagraph(theme = 'general', sentenceCount = 4) {
  const sentences = getRandomSentences(theme, sentenceCount);
  return sentences.join(' ');
}

/**
 * Generate Lorem Bangla text
 * @param {object} options
 * @param {'paragraphs'|'sentences'|'words'|'headings'|'list'} options.type
 * @param {number} options.count
 * @param {string} options.theme - key from THEMES
 * @param {boolean} options.startWithLorem - prepend classic "লোরেম ইপসাম..." style intro
 */
export function generateLoremBangla(options = {}) {
  const {
    type = 'paragraphs',
    count = 3,
    theme = 'general',
    sentencesPerPara = 4,
  } = options;

  const n = Math.max(1, Math.min(count, 20));

  switch (type) {
    case 'paragraphs': {
      const paras = Array.from({ length: n }, () =>
        buildParagraph(theme, sentencesPerPara)
      );
      return paras.join('\n\n');
    }

    case 'sentences': {
      const sentences = getRandomSentences(theme, n);
      return sentences.join('\n');
    }

    case 'words': {
      const allWords = Object.values(THEMES).flatMap(t =>
        t.sentences.flatMap(s =>
          s.replace(/[।॥.!?,;:]/g, '').split(/\s+/).filter(Boolean)
        )
      );
      const shuffled = [...allWords].sort(() => Math.random() - 0.5);
      return shuffled.slice(0, n).join(' ');
    }

    case 'headings': {
      const pool = HEADINGS[theme] || HEADINGS.general;
      const shuffled = [...pool].sort(() => Math.random() - 0.5);
      return shuffled.slice(0, n).join('\n');
    }

    case 'list': {
      const shuffled = [...LIST_ITEMS].sort(() => Math.random() - 0.5);
      return shuffled.slice(0, n).map((item, i) => `${i + 1}. ${item}`).join('\n');
    }

    default:
      return buildParagraph(theme, sentencesPerPara);
  }
}

